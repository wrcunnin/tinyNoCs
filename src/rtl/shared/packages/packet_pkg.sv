package packet_pkg;

  parameter int unsigned AddressWidth = 32;

  parameter int unsigned PayloadWidth = 64;

  // TODO(wrcunnin): What's the best way to have this?
  //  This needs to be equal to the max DepthBits of all
  //  the FIFO router instances. Maybe we just set this to
  //  32 for simulation and fine tune it for synthesis?
`ifndef SYNTHESIS
  parameter int unsigned IdWidth = 32;
`else
  parameter int unsigned IdWidth = 4;
`endif

  // TODO(wrcunnin): What's the best way to do this?
  // I am struggling with finding how to best use the endpoints number
  // For now, I am sticking to 16 endpoints, so if anyone wants to
  // change this, you need to make sure this works.
  parameter int unsigned NumEndpoints   = 16;
  parameter int unsigned EndpointIdBits = $clog2(NumEndpoints);

  typedef logic [AddressWidth-1:0] addr_t;

  typedef logic [PayloadWidth-1:0] payload_t;

  typedef logic [IdWidth-1:0] id_t;

  typedef logic [EndpointIdBits-1:0] endpoint_id_t;

  typedef enum int unsigned {
    kRing = 32'd0,
    kMesh = 32'd1
  } network_type_t;

  // Used by FIFO routers to prepackage data, i.e. before going out
  // onto the network, or to initialize requests
  typedef struct packed {
`ifndef SYNTHESIS
    logic [30:0] padding;
`endif

    // Determines if packet is writing or reading
    logic wen;

    // ID within FIFO for packet
    id_t id;

    // Address packet is going to
    addr_t addr;

    // Payload for the packet
    payload_t payload;
  } packet_t;

  typedef struct packed {
    // Indicates if a packet was a request or reponse
    // - Request is a packet generated by an external write
    // - Reponse is a packet generated by a request packet
    logic request;

    // Coordinate ID of the router where packet originated from
    // x - idx 0
    // y - idx 1
    endpoint_id_t [1:0] src_id;

    // Coordinate ID of the router where packet is going to
    // x - idx 0
    // y - idx 1
    endpoint_id_t [1:0] dst_id;

    // Packet data/information
    packet_t packet;
  } net_packet_t;

  parameter int unsigned NetPacketBits = $bits(net_packet_t);

endpackage
